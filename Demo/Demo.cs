    public static void Init()
    {
        _anim?.Dispose();
        // 💡 baseDirをLumen/Demoに固定。埋め込みテキストの絶対パスは無視され、
        //    ファイル名だけを使ってこのフォルダ配下から画像を探す。
        _anim = Aup2Anim.LoadFromText(EmbeddedAup2, "Lumen/Demo");
        _elapsed = 0f;
        _confirmed = false;
        _fadeState = FadeState.None;
        _fadeTimer = 0f;
        _cKeyWasDown = false;
        _serviceCoinActive = false;
        Coin.ResetInserted();

        // 💡 コイン投入音・サービスコイン投入音は初回のみロード (Result画面のBGM読み込みと同じMusicTrack経由)
        if (!_soundsLoaded)
        {
            const string coinPath = "Lumen/2.sound/Demo/Coin.ogg";
            const string servicePath = "Lumen/2.sound/Demo/Service.ogg";
            if (File.Exists(coinPath)) _coinSound = MusicTrack.Load(coinPath);
            if (File.Exists(servicePath)) _serviceSound = MusicTrack.Load(servicePath);
            _soundsLoaded = true;
        }
    }

    public static void Update(float dt)
    {
        if (_anim == null)
        {
            // aup2の読み込みに失敗した場合は即座にスキップしてタイトルへ
            _confirmed = true;
            return;
        }

        // 💡 暗転中はここで専用処理(アニメの時間は進めない)
        if (_fadeState != FadeState.None)
        {
            _fadeTimer += dt;
            if (_fadeTimer >= FADE_DURATION)
            {
                _fadeTimer = 0f;
                switch (_fadeState)
                {
                    case FadeState.FadeOutForLoop:
                        // 暗転しきったので先頭に巻き戻して暗転から復帰(フェードイン)
                        _elapsed = 0f;
                        _fadeState = FadeState.FadeIn;
                        break;
                    case FadeState.FadeOutForSkip:
                        // 暗転しきったのでタイトルへ確定
                        _confirmed = true;
                        _fadeState = FadeState.None;
                        break;
                    case FadeState.FadeIn:
                        _fadeState = FadeState.None;
                        break;
                }
            }
            return;
        }

        _elapsed += dt;

        // 💡 コイン投入 (Cキー = サービスコイン投入)。フリープレイ時は投入不要なので無視
        //    自前エッジ検出 (_cKeyWasDown) ではなく、Raylib.IsKeyPressed を直接使用する。
        //    もし Update() が1フレームに複数回呼ばれる設計でも、IsKeyPressed はそのフレーム内で
        //    一度だけ true を返すため、多重カウントを防げる。
        if (!Coin.FreePlay && Raylib.IsKeyPressed(KeyboardKey.C))
        {
            Coin.AddCoin();
            PlaySeRestart(_coinSound);
        }

        // 💡 サービスコイン投入 (Xキー)。基本はCキーと同じくコインを1枚加算するが、
        //    中央のコイン枚数表示を以降ずっと濃い赤で表示する演出と専用SEを付ける。
        if (!Coin.FreePlay && Raylib.IsKeyPressed(KeyboardKey.X))
        {
            Coin.AddCoin();
            _serviceCoinActive = true;
            PlaySeRestart(_serviceSound);
        }

        if (Coin.FreePlay)
        {
            // 💡 フリープレイ時: ドン入力(SettingsPanel側のキーコンフィグに準拠)でスキップ可能。暗転してから遷移する
            if (SettingsPanel.IsAnyDonPressed())
            {
                _fadeState = FadeState.FadeOutForSkip;
                _fadeTimer = 0f;
                return;
            }
        }
        else
        {
            // 💡 コイン投入モード: 必要枚数に達したら自動で暗転してタイトルへ
            if (Coin.IsReadyToStart)
            {
                _fadeState = FadeState.FadeOutForSkip;
                _fadeTimer = 0f;
                return;
            }
        }

        // 💡 aup2の尺(Duration)を超えたら暗転してからループ再生する
        double duration = _anim.Duration;
        if (duration > 0 && _elapsed >= (float)duration)
        {
            _fadeState = FadeState.FadeOutForLoop;
            _fadeTimer = 0f;
        }
    }

    public static void Draw()
    {
        Raylib.ClearBackground(Color.Black);
        _anim?.Draw(0, 0, Program.VirtualWidth, Program.VirtualHeight, _elapsed, Color.White);

        DrawBottomText();

        if (_fadeState != FadeState.None)
        {
            float p = Math.Clamp(_fadeTimer / FADE_DURATION, 0f, 1f);
            // FadeOutForLoop / FadeOutForSkip: 0→1で暗くなる。FadeIn: 1→0で明るくなる
            float alphaP = _fadeState == FadeState.FadeIn ? 1f - p : p;
            byte a = (byte)(255 * alphaP);
            Raylib.DrawRectangle(0, 0, Program.VirtualWidth, Program.VirtualHeight, new Color((byte)0, (byte)0, (byte)0, a));
        }
    }

    // 💡 下部の状態表示 (左:1人プレイ / 中央:状態メッセージ / 右:2人プレイ)
    private const float BOTTOM_ANCHOR_L = 440f;
    private const float BOTTOM_ANCHOR_C = 985f;
    private const float BOTTOM_ANCHOR_R = 1575f;
    private const float BOTTOM_LINE1_Y = 1030f;
    private const float BOTTOM_LINE2_Y = 1030f;
    private const float BOTTOM_SINGLE_Y = 1030f;
    private const float BOTTOM_FONT_SIZE = 40f;
    private const float OUTLINE_THICKNESS = 8f;
    private const float PRICE_BLINK_STATIC_SECONDS = 2f;   // 点灯したままの時間
    private const float PRICE_BLINK_FADE_OUT_SECONDS = 0.5f; // 消灯にかける時間
    private const float PRICE_BLINK_FADE_IN_SECONDS = 0.5f;  // 点灯に戻すのにかける時間
    private const float PRICE_BLINK_CYCLE = PRICE_BLINK_STATIC_SECONDS + PRICE_BLINK_FADE_OUT_SECONDS + PRICE_BLINK_FADE_IN_SECONDS;

    private static void DrawBottomText()
    {
        if (Coin.FreePlay)
        {
            DrawCenteredOutline("太鼓をたたいてスタート！", BOTTOM_ANCHOR_L, BOTTOM_SINGLE_Y, 1f);
            DrawCenteredOutline("フリープレイ", BOTTOM_ANCHOR_C, BOTTOM_SINGLE_Y, 1f);
            DrawCenteredOutline("太鼓をたたいてスタート！", BOTTOM_ANCHOR_R, BOTTOM_SINGLE_Y, 1f);
            return;
        }

        float blinkAlpha = PriceBlinkAlpha();

        // --- 左 (1人プレイ側) ---
        if (Coin.IsReadyToStart)
        {
            DrawCenteredOutline("太鼓をたたいてスタート！", BOTTOM_ANCHOR_L, BOTTOM_SINGLE_Y, 1f);
        }
        else
        {
            DrawCenteredOutline($"1人プレイ    {ToFullWidth(Coin.Remaining1P)} コイン", BOTTOM_ANCHOR_L, BOTTOM_LINE1_Y, blinkAlpha);
        }

        // --- 中央 (状態メッセージ) ---
        if (Coin.NoCoinInserted)
        {
            DrawCenteredOutline("コインをいれてね！", BOTTOM_ANCHOR_C, BOTTOM_SINGLE_Y, 1f);
        }
        else
        {
            Color? coinTint = _serviceCoinActive
                ? new Color((byte)254, (byte)0, (byte)0, (byte)255) // 濃い赤
                : (Color?)null;
            DrawCenteredOutline($"{ToFullWidth(Coin.InsertedCount)} コイン", BOTTOM_ANCHOR_C, BOTTOM_SINGLE_Y, blinkAlpha, coinTint);
        }

        // --- 右 (2人プレイ側) ---
        if (Coin.IsReadyToStart2P)
        {
            DrawCenteredOutline("太鼓をたたいてスタート！", BOTTOM_ANCHOR_R, BOTTOM_SINGLE_Y, 1f);
        }
        else
        {
            DrawCenteredOutline($"2人プレイ    {ToFullWidth(Coin.Remaining2P)} コイン", BOTTOM_ANCHOR_R, BOTTOM_LINE1_Y, blinkAlpha);
        }
    }

    /// <summary>
    /// 数値を全角数字の文字列に変換する(コイン枚数表示用)。
    /// </summary>
    private static string ToFullWidth(int value)
    {
        string s = value.ToString();
        var sb = new System.Text.StringBuilder(s.Length);
        foreach (char c in s)
        {
            if (c >= '0' && c <= '9')
                sb.Append((char)(c + 0xFEE0)); // 半角数字 → 全角数字 (U+FF10〜U+FF19)
            else
                sb.Append(c);
        }
        return sb.ToString();
    }

    /// <summary>
    /// 「〇人プレイ / 〇コイン」表示用のアルファ値(0〜1)を計算する。
    /// 2秒間点灯 → 0.5秒かけて消灯 → 0.5秒かけて点灯に戻る、を周期的に繰り返す。
    /// </summary>
    private static float PriceBlinkAlpha()
    {
        float t = _elapsed % PRICE_BLINK_CYCLE;

        if (t < PRICE_BLINK_STATIC_SECONDS)
            return 1f;

        t -= PRICE_BLINK_STATIC_SECONDS;
        if (t < PRICE_BLINK_FADE_OUT_SECONDS)
            return 1f - (t / PRICE_BLINK_FADE_OUT_SECONDS); // 1 → 0

        t -= PRICE_BLINK_FADE_OUT_SECONDS;
        return t / PRICE_BLINK_FADE_IN_SECONDS; // 0 → 1
    }

    /// <summary>
    /// 指定したX座標を中心にテキストを黒縁取り付きで描画する(改行なし)。
    /// alpha を指定すると点滅などの透明度演出に使える。
    /// </summary>
    /// <summary>
    /// 効果音(SE)を先頭から鳴らす。連打時に前の再生が残ったまま重ならないよう、
    /// 一度Stopしてから再生し直す。
    /// </summary>
    private static void PlaySeRestart(MusicTrack track)
    {
        if (track == null || !track.Loaded) return;
        track.Stop();
        track.Play();
    }

    private static void DrawCenteredOutline(string text, float anchorX, float y, float alpha, Color? tint = null)
    {
        // 💡 spacing=0 で計測。以前は計測幅に+4pxのバッファを足していたが、
        //    その分だけ中心がずれて見えていたため削除し、実測幅ぴったりで中央揃えする。
        Vector2 size = Raylib.MeasureTextEx(G.Font, text, BOTTOM_FONT_SIZE, 0);
        float x = anchorX - size.X * 0.5f;

        Color baseColor = tint ?? new Color((byte)255, (byte)255, (byte)255, (byte)255);
        Color textColor = new Color(baseColor.R, baseColor.G, baseColor.B, (byte)(255 * alpha));
        Color outlineColor = new Color((byte)0, (byte)0, (byte)0, (byte)(255 * alpha));

        // 💡 縁取りの太さ(OUTLINE_THICKNESS)が反映されるよう、引数の順番を修正。
        // 一般的な DrawTextWithOutline 実装に合わせて、spacing(0) を最後に、thickness をその前に配置します。
        G.DrawTextWithOutline16(G.Font, text, new Vector2(x, y), BOTTOM_FONT_SIZE, textColor, outlineColor, OUTLINE_THICKNESS, 0);
    }

    public static void ResetState()
    {
        _confirmed = false;
        _elapsed = 0f;
        _fadeState = FadeState.None;
        _fadeTimer = 0f;
        _serviceCoinActive = false;
        _anim?.Dispose();
        _anim = null;
    }
